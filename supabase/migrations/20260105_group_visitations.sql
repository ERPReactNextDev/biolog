-- ── STEP 4 · notification type for group visits ───────────────────────────
-- public.notifications.type has a CHECK that predates this feature, so a group
-- visit notification cannot be inserted until 'group_visit' is allowed.
--
-- Reusing an existing type was rejected deliberately: 'ob_submitted' is what
-- drives the ADMIN bell (lib/notifications.ts ADMIN_BELL_TYPES), so filing
-- group visits under it would push "New group visit" cards into the OB Approvals
-- queue and hide real OB requests among them.

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'notifications_type_check'
  ) THEN
    ALTER TABLE public.notifications DROP CONSTRAINT notifications_type_check;
    ALTER TABLE public.notifications
      ADD CONSTRAINT notifications_type_check
      CHECK (type IN ('ob_approved','ob_declined','ob_submitted','gps_reviewed','group_visit'));
    RAISE NOTICE 'notifications.type now accepts group_visit';
  ELSE
    RAISE NOTICE 'notifications_type_check already exists — verify it allows ''group_visit''';
  END IF;
END $$;


